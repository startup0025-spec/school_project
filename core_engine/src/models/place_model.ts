/**
 * 부산 수변 공간 및 쉼터 데이터 모델 정의
 *
 * 이 파일은 외부 의존성이 전혀 없는 순수 타입(Type) 정의 파일입니다.
 * 다른 모든 코어 엔진 모듈(local_places, api, busan_api, kma_api 등)이
 * 이 규격을 import하여 사용합니다.
 *
 * 근거 문서:
 *   - 교육청 대회용 앱 간단 설계서.txt (라인 85, 98~105, 107~109, 121)
 *   - 앱 UI, UX 설명서.txt (섹션 3.2, 3.3, 4.3, 6.3)
 */

/**
 * 소리화(Sonification) 앰비언트 오디오 분기용 물 타입.
 *
 * UX 3.2항: "물소리 종류(시냇물 / 강물 / 바다)를 칩 버튼으로 선택하면
 *           설명과 파형 느낌이 따라 바뀝니다."
 * 설계서 53~55라인: ambient_sea.mp3, ambient_river.mp3, white_noise_wind.mp3
 *
 * - 'stream' → ambient_river.mp3 (시냇물/소하천)
 * - 'river'  → ambient_river.mp3 (큰 하천, 탁도/수위 데이터 연동)
 * - 'sea'    → ambient_sea.mp3   (바다, 파고 데이터 연동)
 * - 'none'   → 수변이 아닌 내륙 쉼터 (오디오 소리화 미적용)
 */
export type WaterType = 'stream' | 'river' | 'sea' | 'none';

/**
 * 부산 수변 공간 및 쉼터의 단일 장소 데이터 구조체.
 *
 * 이 인터페이스는 앱의 DNA입니다. local_places.ts의 하드코딩 데이터부터
 * api.ts의 거리 연산, geofencing_service.ts의 반경 감지,
 * kma_api.ts의 풍속 조회, busan_api.ts의 수질 조회,
 * notification_service.ts의 환영/경고 알림까지 —
 * 모든 모듈이 이 하나의 규격에 의존합니다.
 */
export interface Place {
  /** 고유 식별자 (예: 'place-dongbaek') */
  id: string;

  /** 장소명 (예: '해운대 동백섬') */
  name: string;

  /** 위도 — Haversine 거리 연산 및 지도 핀 렌더링용 */
  latitude: number;

  /** 경도 — Haversine 거리 연산 및 지도 핀 렌더링용 */
  longitude: number;

  /**
   * 장소 설명 — 반말+평서문의 서정적 텍스트.
   *
   * UX 4.3항: "반말 + 평서문. 명령하거나 조바심 내지 않습니다."
   * UX 3.3항: "카드에는 장소 이름, 짧은 설명, 도보 시간만 들어 있습니다."
   * 설계서 109라인: "상업적 키워드(맛집, 카페, 웨이팅)를 배제"
   *
   * 예: "파도 소리만 들리는 고요한 해안 산책로야."
   */
  description: string;

  /**
   * 물의 종류 — 오디오 엔진이 어떤 앰비언트 파일을 재생할지 결정.
   *
   * UX 3.2항 & 설계서 53~55라인 근거.
   */
  waterType: WaterType;

  /**
   * 카드/배경 이미지 URL.
   *
   * UX 6.3항: 1순위 부산시/관광공사 API 실제 사진,
   *          2순위 생성형 AI(Pollinations 등) 폴백 이미지.
   * 런타임에 동적으로 채워질 수 있으므로 optional.
   */
  imageUrl?: string;

  /**
   * 감성 필터링 태그 배열.
   *
   * 설계서 109라인: "평온 키워드(한적한, 쉼터, 산책, 고요)가 매칭된
   *               청정 수변 좌표 배열만 생성하여 보유."
   *
   * 예: ['한적한', '산책', '고요']
   */
  tags?: string[];

  /**
   * 지오펜싱 인식 반경 (미터 단위).
   *
   * 설계서 121라인: "특정 수변 반경 진입 이벤트 발생 시"
   * 바다(다대포)는 규모가 크므로 500m, 도심 하천(온천천)은 100m 등
   * 장소별로 개별 제어해야 오작동을 방지할 수 있음.
   */
  geofenceRadius: number;

  /**
   * 기상청 단기예보(풍속 WSD) 조회 전용 격자 X 좌표.
   *
   * 설계서 104라인: "기상청 단기예보 조회 서비스 (현재 풍속 WSD 데이터 추출)"
   * 기상청 API는 위경도를 직접 받지 않고 자체 격자 좌표계(nx, ny)만 사용.
   * 런타임 변환 연산을 회피하기 위해 미리 하드코딩.
   * 수변이 아닌 장소(waterType: 'none')는 풍속 연동 불필요 → optional.
   */
  kmaNx?: number;

  /**
   * 기상청 단기예보(풍속 WSD) 조회 전용 격자 Y 좌표.
   * kmaNx와 항상 쌍으로 사용됨.
   */
  kmaNy?: number;

  /**
   * 기상청 기상특보(호우/풍랑 경보) 맵핑용 행정구역명.
   *
   * 설계서 105라인: "기상청 기상특보 현황 조회 서비스
   *               (부산 지역 호우/풍랑 경보 추출 → 안전 가드 연동)"
   * 기상특보는 격자가 아니라 행정구역 단위로 발령됨.
   *
   * 예: '해운대구', '사하구', '동래구'
   */
  district: string;

  /**
   * 부산시 하천 수질/수위 자동측정망 API 조회용 측정소 이름.
   *
   * 설계서 98~99라인: "부산광역시 주요 하천 수위 정보 API"
   *                  "부산광역시 하천 수질 자동측정망 정보 API (수온, 탁도 추출)"
   * 부산시 API는 위경도가 아니라 측정소 명칭(문자열)으로 데이터를 조회.
   * 바다 장소(waterType: 'sea')는 하천 측정소가 없으므로 optional.
   *
   * 예: '온천천', '수영강', '낙동강하구'
   */
  waterStationName?: string;
}

